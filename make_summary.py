#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""make_summary.py — 오늘 결과 전체를 발표용 마크다운 한 장으로"""
import os, json
H = os.path.expanduser("~/이윤우")
def L(f):
    p=os.path.join(H,f)
    return json.load(open(p,encoding="utf-8")) if os.path.exists(p) else {}
hari={}; qwen={}
for f in ["reportA.json","reportB.json","reportC.json"]: hari.update(L(f))
for f in ["reportQ1.json","reportQ2.json"]: qwen.update(L(f))

out=[]
w=out.append
w("# 실제 병원 동의서 기반 검증 결과\n")
w("경기도의료원 공개 수술 동의서 13건 · snuh/hari-q3-8b, Qwen/Qwen3-8B\n")

w("## 1. 데이터 범위\n")
w("| 구분 | 합성 문서 | 실제 동의서 |\n|---|---|---|")
w("| 건수 | 3건 | 13건 |")
w("| 평균 분량 | 286자 | 2,384자 (**8.3배**) |")
w("| 서식·표·빈칸 | 없음 | 있음 |")
w("| 문서 결함 | 없음 | 1건 발견 |\n")

w("## 2. 문서 변환 성능 (Scope ①)\n")
w("| 문서 | hari 사실 | Qwen3 사실 |\n|---|---|---|")
for n in sorted(set(hari)&set(qwen), key=lambda x:(len(x),x)):
    w(f"| {n} | {hari[n]['사실보존']:.1f}% | {qwen[n]['사실보존']:.1f}% |")
mh=sum(hari[n]['사실보존'] for n in hari)/len(hari)
mq=sum(qwen[n]['사실보존'] for n in qwen)/len(qwen)
w(f"| **평균** | **{mh:.1f}%** | **{mq:.1f}%** |\n")
w(f"- 합성 문서 기준 차이 2.8%p → 실제 문서에서 **{mq-mh:.1f}%p**로 확대")
w("- 길이 교란(Qwen 출력이 김) 보정 후에도 우위 유지, doc9는 더 짧게 쓰고도 +10.9%p\n")

w("## 3. 실제 문서에서만 드러난 실패 3종\n")
w("| 유형 | 사례 | 합성에서 발견 가능? |\n|---|---|---|")
w("| 문서 오염 | doc1 골절 동의서에 갑상선 설명 53자 인쇄 | 불가 |")
w("| 빈칸 수치 창작 | doc1·doc11 모두 소요시간을 \"약 1시간\"으로 | 불가 (빈칸 없음) |")
w("| 메타 발화 | \"물론입니다\" **13/13 문서** | 부분적 |\n")
w("- 수치 검증: 단위 보유 93건 중 보존 89 / **변조 0** / 창작 3 → 보존율 95.7%")
w("- 두 모델이 **동일하게 3건씩, 같은 문서에서** 창작 → 모델 교체로 해결 불가\n")

w("## 4. 다국어 번역 검증 (Scope ②)\n")
w("AI Hub 의료 말뭉치로 용어 대역 사전 구축 후 자동 채점\n")
w("| 언어 | 용어 정확도 |\n|---|---|")
w("| 영어 | 125/130 = 96.2% |")
w("| 중국어 | 128/130 = 98.5% |")
w("| 일본어 | 127/130 = 97.7% |\n")
w("**수동 검토 결과 실제 오역 1건 · 누락 1건 (미검출 10건 중 8건은 사전 오탐)**\n")
w("### 오염 문장의 언어별 처리\n")
w("| 언어 | 결과 |\n|---|---|")
w("| 영어 | 그대로 번역 — The thyroid is an organ shaped like a butterfly… |")
w("| 중국어 | 그대로 번역 — 甲状腺是位于颈部前方的蝴蝶状器官 |")
w("| 베트남어 | **오역** — Thực quản(식도)로 |")
w("| 일본어 | **누락** — 해당 섹션 사라짐 |\n")
w("- doc13 일본어: 수술명 **치핵 → 痔瘻(치루)** 오역. 환자가 받을 수술 이름이 틀림\n")

w("## 5. 개선하고 측정했다\n")
w("| 프롬프트 | 메타 발화 | 창작 수치 | 수치 보존 |\n|---|---|---|---|")
w("| P0 (현재) | 11건 | 3건 | 100% |")
w("| P1 (메타 억제) | **0건** | **0건** | 91.4% ⚠ |")
w("| P2 (메타+수치) | **0건** | **0건** | **97.0%** |\n")
w("- P1 부작용: 인사말을 빼자 출력이 압축돼 수치 손실 발생 → 지시마다 부작용을 함께 측정해야 함\n")

w("## 6. 한계\n")
w("- 단일 기관 13건. 병원 간 서식 차이 미검증")
w("- 문서 오염은 13건 중 1건 — \"사례 발견\"이며 빈도 주장 아님")
w("- 근거율 지표는 LLM 판사 오탐이 계통적으로 남아 현재 사용 불가")
w("- 베트남어 병렬 자료 없음 — 오역이 확인된 언어를 정량 검증할 수 없음")
w("- KHIDI 공식 서식집은 스캔본이라 OCR 필요\n")

w("## 7. 결론\n")
w("모델을 쓰는 일보다 **모델을 채점하는 일이 어려웠다.**")
w("검증기를 만들 때마다 섹션 번호를 수치로 세고, 조사 붙은 어절을 다른 단어로 세고,")
w("체크리스트를 본문으로 셌다. 그래서 실행 전 점검을 파이프라인에 넣었고,")
w("오늘 하루에만 다섯 번 잡았다.\n")
w("빈칸 창작은 의료 특화 모델과 범용 모델 모두에서 동일하게 발생했다.")
w("**모델 선택이 아니라 출력 이후의 검증 계층으로만 해결된다.**")

p=os.path.join(H,"FINAL_SUMMARY.md")
open(p,"w",encoding="utf-8").write("\n".join(out))
print(f"[저장] {p}\n"); print("\n".join(out))
